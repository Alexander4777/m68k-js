def load_jump_table(musashi_dir):
    path = os.path.join(musashi_dir, "m68ki_instruction_jump_table.h")
    if not os.path.exists(path):
        sys.stderr.write("validate_opcodes: cannot find %s\n" % path)
        return None
    with open(path) as f:
        txt = f.read()
    body = txt[txt.index("{") + 1:txt.rindex("}")]
    names = [x.strip() for x in body.replace("\n", " ").split(",") if x.strip()]
    if len(names) != 0x10000:
        sys.stderr.write("validate_opcodes: unexpected table size %d\n" % len(names))
        return None
    return names


# ---------------------------------------------------------------------------
#  Minimal 68000 instruction length decoder.
#
#  It only needs to know how many bytes each opcode occupies so that the
#  validator can walk a ROM and find the opcodes that are really
#  *executed*.  The table below was derived from the Musashi opcode
#  handlers.
# ---------------------------------------------------------------------------

def _build_length_table():
    tbl = {}

    # Default: every opcode is 2 bytes long.  The loops below then add
    # the extension words for the instructions that need them.
    for op in range(0x10000):
        tbl[op] = 0

    # ------------------------------------------------------------------
    #  MOVE.<sz>
    #
    #  Musashi encodes the two effective addresses as
    #
    #      00 | size(2) | dstmode(3) dstreg(3) | srcmode(3) srcreg(3)
    #
    #  where the *destination* mode/register pair is on the left.  The
    #  special encodings are:
    #
    #    dstmode 000 + dstreg rrr  ->  Dn (rrr)
    #    dstmode 001 + dstreg 000  ->  (xxx).W
    #    dstmode 001 + dstreg 111  ->  (xxx).L
    #    srcmode 111 + srcreg 100  ->  #imm
    #    srcmode 111 + srcreg 000  ->  (xxx).W
    #    srcmode 111 + srcreg 001  ->  (xxx).L
    # ------------------------------------------------------------------
    for size, ext in ((0, 0), (1, 0), (2, 0)):
        imm_size = 1 if size == 0 else (2 if size == 1 else 4)
        for dmode in range(8):
            for dreg in range(8):
                for smode in range(8):
                    for sreg in range(8):
                        op = (size << 12) | (dmode << 9) | (dreg << 6) | \
                             (smode << 3) | sreg
                        extra = ext
                        # destination extension (absolute EA only)
                        if dmode == 0b001 and dreg == 0b111:
                            extra += 4              # (xxx).L
                        elif dmode == 0b001 and dreg == 0b000:
                            extra += 2              # (xxx).W
                        # source extension
                        if smode == 0b111:
                            if sreg == 0b100:
                                extra += imm_size        # immediate
                            elif sreg == 0b001:
                                extra += 4              # (xxx).L
                            elif sreg == 0b000:
                                extra += 2              # (xxx).W
                        tbl[op] = extra

    # MOVEM: 0100 1D00 1 mmmrrr  (mode 111 = absolute long -> 4 bytes)
    for op in range(0x10000):
        if (op & 0xFB80) == 0x4880 or (op & 0xFB80) == 0x4C80:
            mode = (op >> 3) & 7
            tbl[op] = 2 + (4 if mode == 7 else 0)

    # Branches: 0101 cond(4) disp(12)  /  0110 disp(16)
    #   The 16 bit form has a zero low byte of the opcode, the 8 bit
    #   form a non zero one.
    for op in range(0x10000):
        if (op & 0xF000) == 0x6000:      # Bcc/BSR/BRA
            tbl[op] = 2 if (op & 0xFF) == 0 else 0
        elif (op & 0xFFF8) == 0x51C8:    # DBcc
            tbl[op] = 2
        elif (op & 0xFFF8) == 0x4E50:    # LINK
            tbl[op] = 2

    # JMP/JSR/LEA/PEA with an absolute long operand
    for op in range(0x10000):
        if (op & 0xFFF8) == 0x4E80:      # JSR/JMP <abs>.L
            tbl[op] = 4
        elif (op & 0xFFF8) == 0x41F0:    # LEA <abs>.L,An
            tbl[op] = 4
        elif (op & 0xFFF8) == 0x4870:    # PEA <abs>.L
            tbl[op] = 4

    # ORI/ANDI/EORI/ADDI/SUBI/CMPI with an immediate operand
    #   0000 ooo0 ss ee mmmrrr : the size is in bits 7-6, the EA mode
    #   in bits 5-3 and the register in bits 2-0.
    for op in range(0x10000):
        if (op & 0xF000) in (0x0000, 0x0200, 0x0400, 0x0600, 0x0A00, 0x0C00):
            size = (op >> 6) & 3
            mode = (op >> 3) & 7
            imm = 1 if size == 0 else (2 if size == 1 else 4)
            if mode == 1:      # (xxx).W
                tbl[op] = 2 + imm
            elif mode == 7:    # (xxx).L
                tbl[op] = 4 + imm
            elif mode == 0:    # Dn
                tbl[op] = imm

    # ADDI/SUBI/CMPI/ANDI/ORI/EORI to CCR/SR carry a 16 bit immediate
    for op in (0x027C, 0x0A7C, 0x007C):
        tbl[op] = 2

    # Static bit operations: opcode + extension word
    for op in range(0x10000):
        if (op & 0xFF00) in (0x0800, 0x0840, 0x0880, 0x08C0):
            tbl[op] = 2

    # TRAP / STOP
    for op in range(0x10000):
        if (op & 0xFFF0) == 0x4E40:     # TRAP
            tbl[op] = 0
        elif op == 0x4E72:              # STOP (has a 16 bit extension)
            tbl[op] = 2

    # MOVE from/to SR and CCR
    for op in range(0x10000):
        if (op & 0xFFC0) in (0x40C0, 0x42C0, 0x44C0, 0x46C0):
            tbl[op] = 0

    # LEA with a (d16,An) or (xxx).W destination needs an extension word
    for op in range(0x10000):
        if (op & 0xFFF8) == 0x41F0:     # LEA
            mode = op & 7
            tbl[op] = 2 if mode in (0, 1, 2, 3, 4) else 4
    return tbl


LENGTH_TABLE = _build_length_table()


def walk_rom(data, org, names):
    """Walk the code of a ROM, yielding (address, opcode, handler)."""
    pc = org
    while pc + 1 < len(data):
        op = (data[pc] << 8) | data[pc + 1]
        handler = names[op]
        yield pc, op, handler
        extra = LENGTH_TABLE.get(op)
        if extra is None:
            return
        pc += 2 + extra


def collect_opcodes(roms_dir, names):
    """Collect every opcode that is really executed by each ROM."""
    opcodes = {}
    illegal = []
    for name in sorted(os.listdir(roms_dir)):
        if not name.endswith(".bin"):
            continue
        with open(os.path.join(roms_dir, name), "rb") as f:
            data = f.read()
        # The reset vector is the first 8 bytes; the code starts at the
        # address stored there.
        if len(data) < 8:
            continue
        org = int.from_bytes(data[4:8], "big")
        for pc, op, handler in walk_rom(data, org, names):
            opcodes.setdefault(op, []).append("%s@%04X" % (name, pc))
            if handler == "m68k_op_illegal":
                illegal.append((name, pc, op))
    return opcodes, illegal


def main():
    roms_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        TESTKIT, "tests", "roms")
    musashi_dir = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_MUSASHI

    names = load_jump_table(musashi_dir)
    if names is None:
        return 2

    opcodes, illegal = collect_opcodes(roms_dir, names)
    errors = 0
    checked = 0

    for op in sorted(opcodes):
        handler = names[op]
        where = ", ".join(sorted(set(opcodes[op]))[:3])

        if op in EXPECTED:
            want = EXPECTED[op][0]
            checked += 1
            if want not in handler:
                print("MISMATCH 0x%04X (%s): Musashi decodes as '%s', expected '%s'  [%s]"
                      % (op, EXPECTED[op][1], handler, want, where))
                errors += 1
            continue

    # Any executed opcode that Musashi decodes as illegal would derail
    # the trace - that is always a bug in the ROM generator.
    for name, pc, op in illegal:
        print("ILLEGAL 0x%04X executed at %s@%04X" % (op, name, pc))
        errors += 1

    print("validate_opcodes: %d opcodes checked, %d mismatches"
          % (checked, errors))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
